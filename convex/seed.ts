export const seedAll = mutation({
  args: {},
  handler: async (ctx) => {
    const turfResult = { inserted: 0 };
    const tResult = { inserted: 0 };

    const existingTurfs = await ctx.db.query("turfs").first();
    if (!existingTurfs) {
      for (const turf of sampleTurfs) {
        await ctx.db.insert("turfs", turf);
        turfResult.inserted++;
      }
    }

    const existingTournaments = await ctx.db.query("tournaments").first();
    if (!existingTournaments) {
      for (const t of sampleTournaments) {
        await ctx.db.insert("tournaments", t);
        tResult.inserted++;
      }
    }

    return {
      turfs: turfResult.inserted,
      tournaments: tResult.inserted,
    };
  },
});
