export const seedTurfs = mutation({
  args: {},
  handler: async (ctx) => {
    const existing = await ctx.db.query("turfs").first();
    if (existing) {
      return { inserted: 0, message: "Turfs already exist. Skipping." };
    }
    let inserted = 0;
    for (const turf of sampleTurfs) {
      await ctx.db.insert("turfs", turf);
      inserted++;
    }
    return { inserted, message: `Inserted ${inserted} turfs.` };
  },
});

